#!/usr/bin/env python3
"""Build frontend/src/lib/schoolExamReferenceData.generated.js from the BaxterEnglish school calendar page.

Run once a semester (the page lists one semester):
  1. Save the rendered page https://baxterenglish.com/schools/calendar/ as Markdown text (any renderer that keeps
     the tables; a JSON file with the text under "result" also works).
  2. python3 scripts/exams/build-school-exam-reference.py PAGE.md 115 1 [PAGES_DIR] > frontend/src/lib/schoolExamReferenceData.generated.js
The page's own tables leave out many schools it links to. PAGES_DIR (optional) holds those schools' own pages, saved
as <slug>.html (the last part of https://baxterenglish.com/schools/<slug>/); a school without rows is read from there.
The page is used with the site owner's consent (Founder 2026-11-27). Rows without a date are skipped, and only
the cities in SCOPE are kept.
"""
import json
import os
import re
import sys


# Founder 2026-11-27: start with the cities the campuses serve. Add a city here and rerun to widen.
SCOPE = ("臺北市", "新北市", "桃園市")

def seq(exam: str) -> int:
    if "期末" in exam or "第三次" in exam or "第3次" in exam:
        return 3
    if "第二次" in exam or "第2次" in exam:
        return 2
    return 1


def parse(text: str, first_year: int) -> list:
    start = text.find("各校段考日期\n")
    rows, city, school = [], None, None
    for line in text[max(start, 0):].split("\n"):
        line = line.strip()
        found = re.match(r"^([一-鿿]{2,4}[市縣])（\d+ 校）$", line)
        if found:
            city = found.group(1)
            continue
        if not line.startswith("|") or line.startswith("| ---") or line.startswith("| 學校"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 4:
            continue
        name = re.sub(r"<[^>]+>", "", cells[0]).strip()
        school = name or school
        days = re.findall(r"(\d{1,2})/(\d{1,2})（.）", cells[3])
        if not days or not city or not school:
            continue
        # Months 8-12 belong to the calendar year the school year starts in, 1-7 to the next one.
        iso = [f"{first_year + (0 if int(m) >= 8 else 1)}-{int(m):02d}-{int(d):02d}" for m, d in days]
        grade, number = cells[1].replace("\\~", "~"), seq(cells[2])
        # A school that lists two unnumbered mid-term rows for one grade means a first and a second exam.
        if number == 1 and "第" not in cells[2] and any(r[:3] == [city, school, grade] and r[4] == 1 and r[5] < iso[0] for r in rows):
            number = 2
        rows.append([city, school, grade, cells[2], number, iso[0], iso[-1]])
    return rows


def school_pages(text: str, pages_dir: str, have: set) -> str:
    """Table lines, in the calendar page's own shape, for linked SCOPE schools that have no rows yet."""
    out, index = [], text[text.find("## 各校行事曆"):]
    parts = re.split(r"\n([一-鿿]{2,4}[市縣])（\d+ 校）\n", index)
    for city, block in zip(parts[1::2], parts[2::2]):
        if city not in SCOPE:
            continue
        out.append(f"{city}（0 校）")
        for slug, name in re.findall(r'<a href="https://baxterenglish\.com/schools/([a-z0-9-]+)/">([^<]+)</a>', block):
            if (city, name) in have or not os.path.isfile(os.path.join(pages_dir, slug + ".html")):
                continue
            page = open(os.path.join(pages_dir, slug + ".html"), encoding="utf-8", errors="replace").read()
            table = re.search(r"段考日程表.*?<tbody>(.*?)</tbody>", page, re.S)
            for row in re.findall(r"<tr>(.*?)</tr>", table.group(1), re.S) if table else []:
                cells = [re.sub(r"<[^>]+>", "", c).strip() for c in re.findall(r"<t[hd][^>]*>(.*?)</t[hd]>", row, re.S)]
                if len(cells) == 3 and re.search(r"期中|期末|段考|定期|月考|評量", cells[1]):
                    out.append(f"| {name} | {cells[0]} | {cells[1]} | {cells[2]} |")
    return "\n".join(out)


def main() -> None:
    path, year, semester = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
    text = open(path, encoding="utf-8").read()
    try:
        text = json.loads(text)["result"]
    except (ValueError, KeyError, TypeError):
        pass
    rows = [r for r in parse(text, year + 1911) if r[0] in SCOPE]
    if len(sys.argv) > 4:
        extra = school_pages(text, sys.argv[4], {(r[0], r[1]) for r in rows})
        rows += [r for r in parse("各校段考日期\n" + extra, year + 1911) if r[0] in SCOPE]
        rows.sort(key=lambda r: SCOPE.index(r[0]))  # stable: keeps each school's rows together, cities in SCOPE order
    if len(rows) < 500:
        sys.exit(f"only {len(rows)} rows parsed: the page layout probably changed")
    out = [
        "// GENERATED by scripts/exams/build-school-exam-reference.py; do not edit by hand.",
        f"// Reference school exam dates, {year} 學年第 {semester} 學期, compiled from the BaxterEnglish school calendar",
        "// (https://baxterenglish.com/schools/calendar/), used with their consent per the Founder. Reference only: the",
        "// panel offers these to a director, who still saves each date; the school's own announcement wins.",
        "// Rows are [city, school, grade, exam, seq, start, end].",
        "export default {", f"  year: {year},", f"  semester: {semester},", "  source: 'BaxterEnglish 各校行事曆',", "  rows: [",
    ]
    out += ["    " + json.dumps(r, ensure_ascii=False, separators=(",", ":")) + "," for r in rows]
    out += ["  ],", "};", ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
